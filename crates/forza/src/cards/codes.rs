/// The name for the catalogue: a code absent from the table or a `Low` name gives "".
pub fn name_for(table: &[(u8, &'static str, Conf)], code: u8) -> &'static str {
    match table.iter().find(|t| t.0 == code) {
        Some(&(_, name, Conf::High | Conf::Medium)) => name,
        _ => "",
    }
}
